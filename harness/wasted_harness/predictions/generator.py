"""Picks the best prediction template for the current moment.

Deterministic: everything the generator needs — the catalogue, a clock, a wall
clock — is injected at construction (the same `Callable[[], float]` pattern
`wasted_harness.budget.BudgetGovernor` and `wasted_harness.behavior.roam`'s
engines already use); nothing here reads `time.time()`/`time.monotonic()`
directly, and there is no module-level mutable state. Two instances built with
the same catalogue, the same clock values and the same states/session ids
produce byte-identical decisions (see `test_predictions_generator.py`'s
determinism test).

**Anti-spam, four separate mechanisms (task brief):**

1. A cooldown between ANY two generated predictions (`min_gap_s`).
2. No duplicate `prediction_type` back-to-back, plus a longer per-type
   cooldown (`type_cooldown_s`) so the same question does not resurface every
   few ticks even once the immediate no-repeat has cleared.
3. A cap on concurrently OPEN predictions (`max_concurrent_open`), tracked by
   this generator's own memory of what it has produced and when each one's
   `resolves_at` falls (on the injected monotonic clock) — this package does
   not read prediction status back from the database (settlement/status is a
   different workstream's job), so "open" here means "generated by this
   instance and not yet past its own resolve time".

4. A far longer, separate cooldown for WANTED EVENTS (`event_cooldown_s`,
   default 40x the per-type one), plus a structural rule that an event is
   never generated immediately after another event. The operator's brief is
   explicit — "Keep them special. Do not make every prediction feel like a
   major event." — so rarity is enforced here, as configuration, rather than
   being left to how often a template happens to trigger. `events_enabled`
   turns them off entirely without touching the catalogue.

Ranking (brief §12: uncertainty, watchability, resolution speed, reliability,
novelty) combines each template's own `score(state)` — which already folds in
a real-field uncertainty/watchability proxy, see `catalog.py` — with two more
dimensions only the generator can see: the template's window (shorter =
faster to resolve = better) and how long it has been since this template was
last picked (soft novelty, on top of the hard per-type cooldown above).

An offerable event also gets `event_rank_bonus` added to its rank. That is not
a thumb on the scale for a worse question: an event is gated to at most one per
`event_cooldown_s`, and events run the LONGEST windows in the catalogue, which
the speed term penalises hardest — without the bonus the rarity gate would be
decorative, because the event would lose to a 90s question on the rare tick it
was allowed to run at all. Measured on the real catalogue: at two stars with a
fresh gain and full health, `two_star_standoff` ranks 0.74 before the bonus,
behind `loses_the_cops` (0.85) and `survives_a_chase` (0.80) — it would never
once be picked. The bonus is configurable and applies only to templates that
already passed the rarity gate.

**Reward pools, including the boosted ones, are not this module's to write.**
The row carries `is_event` and nothing else reward-related; see `catalog.py`'s
module docstring for where the boost belongs (the layer that funds
`reward_pool`, keyed off exactly this flag) and why settlement cannot apply it.
"""

from __future__ import annotations

import time
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from decimal import Decimal
from typing import Any

from wasted_harness.bridge_client import GameState
from wasted_harness.logsetup import get_logger

from .catalog import PredictionTemplate, RecentEvent, Window

log = get_logger("wasted.predictions.generator")

#: brief §9's own floor/ceiling, used to normalise the "resolution speed" term.
_MIN_WINDOW_S = 30.0
_MAX_WINDOW_S = 300.0


def _speed_score(window: Window) -> float:
    """1.0 for the fastest legal window, 0.0 for the slowest."""
    span = _MAX_WINDOW_S - _MIN_WINDOW_S
    if span <= 0:
        return 1.0
    return max(0.0, min(1.0, 1.0 - (window.total_s - _MIN_WINDOW_S) / span))


def _hud_snapshot(state: GameState) -> dict[str, Any]:
    """`state_context`: the exact frozen `stats.hud` shape (CONTRACTS.md §5),
    reused rather than invented — it is already the harness's own answer to
    "what does the HUD look like right now"."""
    return {
        "health": state.player.health,
        "armor": state.player.armor,
        "wanted": state.player.wanted,
        "cash": state.player.cash,
        "vehicle": state.vehicle.display_name if state.vehicle is not None else None,
        "street": state.location.street,
        "zone": state.location.zone,
        "clock": state.world.clock,
        "weather": state.world.weather,
    }


def _iso(epoch_s: float) -> str:
    return datetime.fromtimestamp(epoch_s, UTC).isoformat()


@dataclass(frozen=True)
class GeneratorConfig:
    """Anti-spam knobs. Defaults are conservative: the shortest legal window
    (§9's 30s floor) is the minimum gap between any two generated predictions,
    and a type does not resurface for three times that."""

    max_concurrent_open: int = 2
    min_gap_s: float = _MIN_WINDOW_S
    type_cooldown_s: float = _MIN_WINDOW_S * 3.0

    #: --- WANTED EVENT rarity, the whole of it, in three named knobs --------
    #: An hour between events: 40x `type_cooldown_s`, and a hard ceiling of 24
    #: a day against the hundreds of ordinary predictions a day the gap/cap
    #: above allow. It is a CEILING, not a schedule — the shipped event
    #: template also has to trigger, and its trigger (the heat hitting this
    #: agent's measured ceiling) fired 17 times in 86.93 h of real recording,
    #: about once every 5 h, so in practice the telemetry is rarer than the
    #: cooldown. Both limits are deliberate: the cooldown is what stops a burst
    #: of two-star moments turning into a burst of "major events".
    event_cooldown_s: float = 3600.0
    #: Kill switch: leaves the catalogue alone, stops events being offered.
    events_enabled: bool = True

    #: --- the reward pool this row commits ---------------------------------
    #: `predictions.reward_pool` is `numeric(38,18) NOT NULL CHECK (> 0)` and
    #: `reward_asset` is `NOT NULL`, both with NO default and nothing filling
    #: them later. Omitting them does not degrade gracefully: every insert is
    #: rejected, `events.py` requeues the row, and the offline queue grows on
    #: the game-loop thread until it starts evicting real event history. So the
    #: generator sets them, because the generator is what creates the row.
    #:
    #: WHOLE token units, matching the column and the operator-facing §6 caps
    #: in `site_config`. Settlement still clamps against those caps, so this is
    #: the pool a prediction ASKS for, not a promise the treasury has to keep.
    #: A string keeps it exact all the way to Postgres — a float would not.
    #: 0.005 TTWO ≈ $1.07 at TTWO $213.89 (Robinhood /rhj/prices, 2026-09-09).
    #:
    #: The unit price is why this is small. TTWO is a tokenized share, not a memecoin: one token is
    #: ~$214, so a pool of "1" — the obvious-looking default this replaced — would have been $214
    #: PER PREDICTION, and at the ~22 predictions/day this catalogue actually generates that is
    #: ~$4,700/day. The whole pool is distributed on every settled prediction, so pool x
    #: predictions-per-day IS the burn rate.
    #:
    #: At 0.005 the burn is ~$23.50/day, and a winner's share lands between $0.21 (5 correct) and
    #: $0.05 (20 correct) — enough that eight to seventeen wins clear the $0.44 minimum claim,
    #: which is roughly a day of watching. Raise it if the audience grows; the even split means a
    #: bigger crowd dilutes each winner rather than costing the treasury more.
    base_reward_pool: str = "0.005"
    #: WANTED EVENTS carry a boosted pool (§13). This is the multiplier, and it
    #: is applied HERE because here is where the pool is funded; settlement only
    #: divides what it is given.
    #: A WANTED EVENT pays 4x the base pool — 0.02 TTWO ≈ $4.28 — which stays under the
    #: max_per_prediction cap so a highlighted round is never silently clamped down to the
    #: ordinary amount.
    event_reward_multiplier: int = 4
    #: Named, not hardcoded — the reward asset is configurable (§1).
    reward_asset: str = "TTWO"
    #: Added to an already-offerable event's rank. See the module docstring for
    #: why an event needs it (its long window loses the speed term outright).
    event_rank_bonus: float = 0.25


@dataclass
class PredictionGenerator:
    """`generate(state, session_id, recent_events)` -> a ready-to-write row, or
    `None`. Never raises on a misbehaving template's `trigger`/`score` — a
    single bad template must not silence every other candidate, let alone the
    caller's main loop (the same "never kill the loop" posture `events.py`
    documents for its own I/O boundary)."""

    catalog: Sequence[PredictionTemplate]
    clock: Callable[[], float] = time.monotonic
    wall_clock: Callable[[], float] = time.time
    config: GeneratorConfig = field(default_factory=GeneratorConfig)

    _last_generated_at: float = field(default=float("-inf"), init=False, repr=False)
    _last_type: str | None = field(default=None, init=False, repr=False)
    _last_event_at: float = field(default=float("-inf"), init=False, repr=False)
    _last_was_event: bool = field(default=False, init=False, repr=False)
    _last_picked_at: dict[str, float] = field(default_factory=dict, init=False, repr=False)
    #: (prediction_type, resolves_at monotonic) for everything this instance
    #: has generated whose window has not yet closed.
    _open: list[tuple[str, float]] = field(default_factory=list, init=False, repr=False)

    def __post_init__(self) -> None:
        seen: set[str] = set()
        for tpl in self.catalog:
            if tpl.prediction_type in seen:
                raise ValueError(
                    f"duplicate prediction_type in catalog: {tpl.prediction_type!r}"
                )
            seen.add(tpl.prediction_type)

    # -- introspection (tests, and any future caller that wants to observe) ---

    @property
    def open_count(self) -> int:
        self._prune_open(self.clock())
        return len(self._open)

    # -- the decision ------------------------------------------------------------

    def generate(
        self,
        state: GameState,
        session_id: str | None,
        recent_events: Sequence[RecentEvent] = (),
    ) -> dict[str, Any] | None:
        """Returns one prediction row, or `None` when nothing should be generated.

        Never generates when `session_id` is `None` (no live session — task
        brief: "If no session is live, generate NOTHING") and never generates
        anything whose `telemetry_rule.kind` is outside the §3 registry (this
        is unreachable in practice: `PredictionTemplate.__post_init__` already
        refuses to construct such a template, so the catalogue cannot contain
        one).
        """
        if session_id is None:
            return None

        now = self.clock()
        self._prune_open(now)

        if now - self._last_generated_at < self.config.min_gap_s:
            return None
        if len(self._open) >= self.config.max_concurrent_open:
            return None

        best: PredictionTemplate | None = None
        best_rank = float("-inf")
        events_offerable = self._events_offerable(now)
        for tpl in self.catalog:
            if tpl.prediction_type == self._last_type:
                continue  # no duplicate prediction_type back-to-back
            if tpl.is_event and not events_offerable:
                continue  # WANTED EVENTS are rare on purpose — see _events_offerable
            last_picked = self._last_picked_at.get(tpl.prediction_type, float("-inf"))
            if now - last_picked < self.config.type_cooldown_s:
                continue
            try:
                if not tpl.trigger(state, recent_events):
                    continue
            except Exception as exc:
                # A single misbehaving template must not take down the picker
                # (or the main loop calling it); it is simply not a candidate
                # this tick.
                log.warning(
                    "prediction template trigger raised; skipping it this tick",
                    extra={
                        "kv": {
                            "prediction_type": tpl.prediction_type,
                            "error": f"{type(exc).__name__}: {exc}"[:200],
                        }
                    },
                )
                continue
            rank = self._rank(tpl, state, now, last_picked)
            if rank > best_rank:
                best, best_rank = tpl, rank

        if best is None:
            return None

        row = self._build_row(best, state, session_id)
        self._last_generated_at = now
        self._last_type = best.prediction_type
        self._last_picked_at[best.prediction_type] = now
        if best.is_event:
            self._last_event_at = now
        self._last_was_event = best.is_event
        self._open.append((best.prediction_type, now + best.window.total_s))
        return row

    # -- WANTED EVENT rarity ------------------------------------------------------

    def _events_offerable(self, now: float) -> bool:
        """Whether ANY `is_event` template may be offered on this tick.

        Three independent reasons to say no, all of them configuration rather
        than a number buried in the picker: events switched off entirely; the
        previous generated prediction was itself an event (never back-to-back,
        whatever the clock says); or the event cooldown has not elapsed.
        """
        if not self.config.events_enabled:
            return False
        if self._last_was_event:
            return False
        return now - self._last_event_at >= self.config.event_cooldown_s

    # -- ranking (brief §12: uncertainty+watchability, speed, reliability, novelty) --

    def _rank(
        self, tpl: PredictionTemplate, state: GameState, now: float, last_picked: float
    ) -> float:
        try:
            quality = max(0.0, min(1.0, float(tpl.score(state))))
        except Exception:
            quality = 0.0
        speed = _speed_score(tpl.window)
        if last_picked == float("-inf") or self.config.type_cooldown_s <= 0:
            # Never picked, or the operator turned the per-type cooldown off —
            # in which case there is no scale on which to be "stale", so
            # novelty stops discriminating instead of dividing by zero. (It
            # did divide by zero before the WANTED EVENT tests exercised a
            # `type_cooldown_s=0` config; that would have escaped `generate`
            # and reached the main loop, which nothing else here is allowed to
            # do.)
            novelty = 1.0
        else:
            novelty = max(0.0, min(1.0, (now - last_picked) / self.config.type_cooldown_s))
        rank = 0.5 * quality + 0.2 * speed + 0.2 * tpl.reliability + 0.1 * novelty
        if tpl.is_event:
            # Only reachable for an event that already passed the rarity gate.
            rank += self.config.event_rank_bonus
        return rank

    # -- bookkeeping --------------------------------------------------------------

    def _prune_open(self, now: float) -> None:
        self._open = [(pt, resolves_at) for pt, resolves_at in self._open if resolves_at > now]

    def _build_row(
        self, tpl: PredictionTemplate, state: GameState, session_id: str
    ) -> dict[str, Any]:
        opened = self.wall_clock()
        locks = opened + tpl.window.lock_delay_s
        resolves = locks + tpl.window.resolve_delay_s
        return {
            "session_id": session_id,
            "question": tpl.question,
            "prediction_type": tpl.prediction_type,
            "state_context": _hud_snapshot(state),
            # Nullable per CONTRACTS-PREDICTIONS §2; this package has no
            # reliable events.id at generation time (buffered inserts return
            # none — see events.py), so it is honestly left null rather than
            # invented.
            "created_from_event": None,
            "opened_at": _iso(opened),
            "locks_at": _iso(locks),
            "resolves_at": _iso(resolves),
            "outcomes": list(tpl.outcomes),
            "telemetry_rule": dict(tpl.telemetry_rule),
            "status": "open",
            # The one reward-adjacent field this package owns: `is_event` is
            # what the site highlights and what the pool-funding layer keys a
            # boosted pool off (catalog.py's module docstring). Written for
            # every row, true or false, rather than left to the column default,
            # so the row says what it is instead of what it forgot to say.
            "is_event": tpl.is_event,
            # NOT NULL in the schema, no default, nothing backfills them. See
            # GeneratorConfig.base_reward_pool for why this package owns them.
            "reward_pool": self._pool_for(tpl),
            "reward_asset": self.config.reward_asset,
        }

    def _pool_for(self, tpl: PredictionTemplate) -> str:
        """The pool this row commits, in whole token units, as an exact string.

        Integer arithmetic on the decimal string rather than float maths: a
        float multiplier turns "0.1" into 0.5000000000000001 on the way to a
        numeric(38,18) column, and a reward that rounds is a reward that lies.
        """
        base = Decimal(self.config.base_reward_pool)
        pool = base * self.config.event_reward_multiplier if tpl.is_event else base
        if pool <= 0:
            raise ValueError(
                f"reward_pool must be > 0 (schema CHECK); got {pool} from "
                f"base_reward_pool={self.config.base_reward_pool!r}"
            )
        return format(pool, "f")
