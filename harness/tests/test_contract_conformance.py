# --- the consumers, against the real first-poll document -----------------------


def test_every_last_task_consumer_handles_the_null_id() -> None:
    """Not just the model: the code that reads `last_task` on the first poll."""
    fresh = GameState.model_validate(_load("state-fresh-load.json"))
    populated = GameState.model_validate(_load("state-populated.json"))

    # Perception: two consecutive fresh polls must not invent a finished task.
    perceptor = Perceptor()
    first = perceptor.observe(fresh)
    assert not first.task_finished and not first.task_failed
    second = perceptor.observe(fresh)
    assert not second.task_finished, "two null task ids are not one task finishing"
    third = perceptor.observe(populated)
    assert not third.task_finished

    # Reflexes that read last_task.type / .status / .id.
    assert StuckDetector().check(fresh) is None
    assert flipped_action(fresh) is None
    assert StrandedEscalator().check(fresh) is not None  # on foot, no task: search
    assert GameRestartDetector().check(fresh) is False

    # The activity runner takes last_task.id straight from the snapshot.
    runner = ActivityRunner(ActivityPicker(random.Random(3)), random.Random(3))
    assert runner.next_step(fresh.last_task.status, fresh.last_task.id) is None


def test_a_real_task_finishing_is_still_detected() -> None:
    """The null-safety must not have blunted the actual signal."""
    running = GameState.model_validate(_load("state-populated.json"))
    done = running.model_copy(deep=True)
    done.last_task.status = "done"
    perceptor = Perceptor()
    perceptor.observe(running)
    delta = perceptor.observe(done)
    assert delta.task_finished and not delta.task_failed


# --- error codes (CONTRACTS v1.2, closed set) ----------------------------------


def _captured_errors() -> list[dict[str, Any]]:
    return _load("errors.json")["captured"]


def test_the_sample_catalog_is_the_v1_2_contract_version() -> None:
    assert _load("errors.json")["contract_version"] == "1.2"


def test_every_v1_2_error_code_is_accounted_for_by_the_bridge() -> None:
    """Both sides enumerate the same closed set."""
    captured = {e["body"]["error"] for e in _captured_errors()}
    deferred = {e["error"] for e in _load("errors.json")["not_capturable_offline"]}
    missing = sorted(set(BRIDGE_ERROR_STATUS) - captured - deferred)
    assert not missing, f"v1.2 codes the bridge never produced or documented: {missing}"


def test_recorded_error_bodies_classify_the_way_the_contract_says() -> None:
    for entry in _captured_errors():
        code = entry["body"]["error"]
        status = entry["status"]
        exc = classify_bridge_error(status, code, entry["body"]["detail"], "GET", "/state")
        if code == "online_session_active":
            assert isinstance(exc, OnlineSessionActiveError), entry["request"]
            continue
        assert isinstance(exc, BridgeApiError), entry["request"]
        assert exc.status == status and exc.error == code
        known = code in BRIDGE_ERROR_STATUS
        if known:
            # The status the bridge actually sent must match our copy of §1.
            assert BRIDGE_ERROR_STATUS[code] == status, (
                f"{code} arrived as {status}, contract says {BRIDGE_ERROR_STATUS[code]}"
            )
        should_retry = (not known) or code in TRANSIENT_BRIDGE_ERRORS
        assert isinstance(exc, BridgeTransientError) is should_retry, (
            f"{entry['request']} -> {code}: retryable={should_retry} expected"
        )


def test_startup_503s_are_transient_and_never_fatal() -> None:
    """not_ready / game_thread_stalled are the normal answers during a load."""
    by_code = {e["body"]["error"]: e for e in _captured_errors()}
    for code in ("not_ready", "game_thread_stalled"):
        assert code in by_code, f"{code} is not in the bridge's recorded errors"
        entry = by_code[code]
        exc = classify_bridge_error(
            entry["status"], code, entry["body"]["detail"], "GET", "/state"
        )
        assert isinstance(exc, BridgeTransientError)
        assert exc.status == 503


def test_an_unknown_code_is_tolerated_as_transient_not_crashed_on() -> None:
    """v1.2: 'consumers must handle unknown codes gracefully'.

    The code below is deliberately invented by this test — it is the one input
    that cannot be recorded, because by definition the bridge does not emit it
    in this contract version. It exercises the tolerance rule, nothing else.
    """
    exc = classify_bridge_error(503, "warp_core_breach", "not a v1.2 code", "GET", "/state")
    assert isinstance(exc, BridgeTransientError)
    assert exc.error == "warp_core_breach"
    assert isinstance(exc, BridgeApiError)  # still carries status/error/detail


# --- the same bodies, over a real socket, through the real client --------------


class _ReplayHandler(BaseHTTPRequestHandler):
    """Serves the bridge's recorded bytes verbatim. No harness code involved."""

    routes: ClassVar[dict[str, tuple[int, bytes]]] = {}

    def do_GET(self) -> None:  # BaseHTTPRequestHandler API name
        status, body = self.routes.get(self.path, (404, b'{"error":"not_found"}'))
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    do_POST = do_GET

    def log_message(self, *_args: Any) -> None:
        pass


@pytest.fixture
def replay_server():
    def start(routes: dict[str, tuple[int, bytes]]) -> str:
        handler = type("_H", (_ReplayHandler,), {"routes": routes})
        server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
        threading.Thread(target=server.serve_forever, daemon=True).start()
        started.append(server)
        host, port = server.server_address[:2]
        return f"http://{host}:{port}"

    started: list[ThreadingHTTPServer] = []
    yield start
    for server in started:
        server.shutdown()
        server.server_close()


def test_client_parses_the_real_bytes_off_a_real_socket(replay_server) -> None:
    """End to end: bridge's recorded response bytes -> HTTP -> GameState/Health."""
    base = replay_server(
        {
            "/state": (200, _raw("state-fresh-load.json")),
            "/health": (200, _raw("health-fresh-load.json")),
        }
    )
    client = BridgeClient(base, timeout_s=2.0, connect_retries=0)
    try:
        state = client.get_state()
        assert state.last_task.id is None and state.last_task.status == "idle"
        assert client.get_health().edition == "unknown"
    finally:
        client.close()


def test_client_raises_the_right_type_for_every_recorded_error(replay_server) -> None:
    for entry in _captured_errors():
        body = json.dumps(entry["body"]).encode()
        base = replay_server({"/state": (entry["status"], body)})
        client = BridgeClient(base, timeout_s=2.0, connect_retries=0)
        code = entry["body"]["error"]
        try:
            with pytest.raises(Exception) as caught:  # exact type asserted below
                client.get_state()
        finally:
            client.close()
        exc = caught.value
        if code == "online_session_active":
            assert isinstance(exc, OnlineSessionActiveError), code
        elif code in TRANSIENT_BRIDGE_ERRORS or code not in BRIDGE_ERROR_STATUS:
            assert isinstance(exc, BridgeTransientError), code
        else:
            assert isinstance(exc, BridgeApiError), code
            assert not isinstance(exc, BridgeTransientError), code


def test_a_stalled_bridge_does_not_stop_the_client_from_recovering(replay_server) -> None:
    """not_ready then a real snapshot: the client must survive the first answer."""
    stalled = next(e for e in _captured_errors() if e["body"]["error"] == "not_ready")
    base = replay_server({"/state": (stalled["status"], json.dumps(stalled["body"]).encode())})
    client = BridgeClient(base, timeout_s=2.0, connect_retries=0)
    try:
        for _ in range(3):
            with pytest.raises(BridgeTransientError):
                client.get_state()
        # The socket is still usable afterwards — no poisoned connection.
        with pytest.raises(BridgeTransientError):
            client.get_state()
    finally:
        client.close()


def test_every_fixture_is_a_real_recording() -> None:
    """CLAUDE.md rule 1: harness/tests/fixtures/ is for real session recordings.

    This used to assert the directory was EMPTY, which was a proxy for the real rule at a time
    when no recording existed yet. Emptiness is the wrong thing to enforce now that real
    recordings live here: it would fail on exactly the fixtures rule 1 permits, while still
    passing the moment someone dropped in a hand-written file under a different extension.

    So it checks the rule itself. Every fixture must carry provenance saying which real session
    it came from and how it was captured, and no bridge contract-sample may be copied in under
    any name — those describe a shape, not a session, and a shape sample masquerading as a
    recording is precisely the invented data rule 1 exists to keep out.
    """
    fixtures = Path(__file__).resolve().parent / "fixtures"

    sample_dir = Path(__file__).resolve().parents[2] / "bridge" / "contract-samples"
    sample_names = {p.name for p in sample_dir.glob("*.json")} if sample_dir.is_dir() else set()

    for path in sorted(fixtures.glob("*.json")):
        assert path.name not in sample_names, (
            f"{path.name} is a bridge contract sample copied into the harness fixtures"
        )
        payload = json.loads(path.read_text())
        provenance = payload.get("_provenance") if isinstance(payload, dict) else None
        assert isinstance(provenance, dict), (
            f"{path.name} has no _provenance block — a fixture must say which real session it "
            f"is a recording of (CLAUDE.md rule 1)"
        )
        for field in ("session_id", "source", "captured_at"):
            assert provenance.get(field), f"{path.name}: _provenance.{field} is missing or empty"


