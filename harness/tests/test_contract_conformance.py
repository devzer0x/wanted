"""Harness models vs the bridge's REAL serialized output (CONTRACTS v1.2).

This is the cross-package test. Everything else in this suite checks the harness
against the harness's own idea of the contract — which is exactly how
`last_task.id: null` got all the way to delivery day: both packages were
internally consistent and disagreed with each other.

The inputs here are the bridge package's own recordings in
``bridge/contract-samples/``: JSON produced by *its compiled DLL* (the same
``SnapshotJson.Serialize`` the game thread publishes ``/state`` with) and by its
real ``BridgeRouter`` over a real HTTP connection. They are bridge output, not
fixtures anybody typed, so a shape drift on either side fails here — in CI, on a
laptop — instead of at 3am on the server.

Deliberately NOT copied into ``harness/tests/fixtures/``: that directory is
reserved for recordings of real game sessions (CLAUDE.md rule 1). These are read
from the bridge path, and the whole module skips with a clear message when the
bridge package is absent.

What these samples are and are not: field names, nesting, JSON types and null
handling are real (produced by the compiled assembly). The world *values*
(coordinates, street names) are assembled by the bridge's own tool because
natives cannot run off the game server. So this file asserts shapes, types and
nullability — never that a number means anything about the game world.
"""

