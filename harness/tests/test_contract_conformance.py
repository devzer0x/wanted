def test_first_poll_of_a_session_validates() -> None:
    """The document that used to crash the harness on its very first poll.

    `last_task.id` and `last_task.type` are null until a task has been posted
    (CONTRACTS v1.2 (a)); the harness's model declared them as required `str`.
    """
    state = GameState.model_validate(_load("state-fresh-load.json"))
    assert state.last_task.id is None
    assert state.last_task.type is None
    assert state.last_task.status == "idle"
    assert state.last_task.detail == ""
    assert state.vehicle is None
    assert state.mission.objective_blip is None
    # v1.2 (b): edition may still be undetermined at this point.
    assert state.bridge.edition == "unknown"
    assert state.bridge.edition in KNOWN_EDITIONS


def test_populated_state_validates_every_optional_branch() -> None:
    state = GameState.model_validate(_load("state-populated.json"))
    assert state.vehicle is not None
    assert state.vehicle.vehicle_class == "Super"  # the `class` alias resolves
    assert state.mission.objective_blip is not None
    assert state.mission.objective_blip.kind == "coord"
    assert state.nearby.vehicles and state.nearby.peds
    assert state.nearby.vehicles[0].vehicle_class == "Emergency"
    assert state.nearby.peds[0].relationship == "hostile"
    assert state.last_task.id == "t-000123"
    assert state.last_task.type == "drive_to"
    assert state.bridge.edition == "legacy"


@pytest.mark.parametrize("name", ["state-fresh-load.json", "state-populated.json"])
def test_no_field_the_bridge_sends_is_dropped_by_the_model(name: str) -> None:
    """A field the bridge emits and the harness silently ignores is a mismatch too.

    The models use extra="ignore" so a *new* bridge field cannot crash the
    harness — which also means it would never be noticed. This catches that.
    """
    sample = _load(name)
    dumped = GameState.model_validate(sample).model_dump(by_alias=True)
    missing = sorted(_keys(sample) - _keys(dumped))
    assert not missing, f"{name}: the harness model drops bridge fields {missing}"


@pytest.mark.parametrize("name", ["state-fresh-load.json", "state-populated.json"])
def test_state_survives_the_round_trip_the_prompt_does(name: str) -> None:
    """main._dynamic_context sends `model_dump_json(by_alias=True)` to the model.

    The nulls have to survive that too, or the brain is told about a task that
    does not exist.
    """
    original = GameState.model_validate(_load(name))
    reparsed = GameState.model_validate_json(original.model_dump_json(by_alias=True))
    assert reparsed == original
    payload = json.loads(original.model_dump_json(by_alias=True))
    assert payload["last_task"]["id"] == json.loads(_raw(name))["last_task"]["id"]


