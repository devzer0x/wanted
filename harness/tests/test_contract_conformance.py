# --- locating the bridge's recordings -----------------------------------------

SAMPLES_DIR = Path(
    os.environ.get(
        "WASTED_BRIDGE_SAMPLES",
        Path(__file__).resolve().parents[2] / "bridge" / "contract-samples",
    )
)

_SKIP_REASON = (
    f"bridge contract samples not found at {SAMPLES_DIR}. They are generated by "
    f"bridge/tools/offline-checks/run.sh from the compiled WastedBridge.dll. "
    f"Without them the harness cannot check its models against real bridge bytes; "
    f"regenerate them in the bridge package, or point WASTED_BRIDGE_SAMPLES at them."
)

pytestmark = pytest.mark.skipif(not SAMPLES_DIR.is_dir(), reason=_SKIP_REASON)


def _raw(name: str) -> bytes:
    path = SAMPLES_DIR / name
    if not path.exists():
        pytest.skip(f"{path} missing — regenerate with bridge/tools/offline-checks/run.sh")
    return path.read_bytes()


def _load(name: str) -> Any:
    return json.loads(_raw(name))


# --- key coverage --------------------------------------------------------------


def _keys(node: Any, prefix: str = "") -> set[str]:
    """Every dotted key path in a JSON document (list items collapse to [])."""
    out: set[str] = set()
    if isinstance(node, dict):
        for k, v in node.items():
            path = f"{prefix}.{k}" if prefix else k
            out.add(path)
            out |= _keys(v, path)
    elif isinstance(node, list):
        for item in node:
            out |= _keys(item, f"{prefix}[]")
    return out


